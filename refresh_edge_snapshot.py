"""Refresh the edge node snapshot bundled in src/prewarm.py.

The Lambda uses the snapshot when the edge node list URL cannot be fetched.
Only country -> city -> node codes is kept. Run `python3 build.py` afterwards.

Usage: python3 refresh_edge_snapshot.py [edge-list-url]
"""

import datetime
import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent
SOURCE = ROOT / "src" / "prewarm.py"
DEFAULT_URL = "https://static.cloudping.cloud/cdn/cloudfront-edge-locations.json"
NODE_CODE_RE = re.compile(r"^[A-Z]{3}[0-9]{1,3}-[A-Z0-9]{1,6}$")  # same as prewarm.py
BLOCK_RE = re.compile(r"^# BEGIN EDGE SNAPSHOT.*?^# END EDGE SNAPSHOT\n", re.S | re.M)
LINE_WIDTH = 110


def fetch(url):
    """Return {country: {city: [node codes]}}, sorted, without cities that have no nodes."""
    request = urllib.request.Request(url, headers={"User-Agent": "cloudfront-prewarm/1.0"})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = json.load(response)
    locations = {}
    for location in data["edge_locations"]:
        country = str(location.get("country", "")).strip()
        city = str(location.get("city", "")).strip()
        codes = locations.setdefault(country, {}).setdefault(city, [])
        for node in location.get("active_nodes") or []:
            code = str(node.get("code", "")).upper()
            if NODE_CODE_RE.match(code) and code not in codes:
                codes.append(code)
    result = {}
    for country in sorted(locations):
        cities = {city: codes for city, codes in sorted(locations[country].items()) if codes}
        if cities:
            result[country] = cities
    return result


def _codes(codes, indent):
    """Render a code list, wrapped to LINE_WIDTH."""
    one_line = json.dumps(codes)
    if indent + len(one_line) <= LINE_WIDTH:
        return [one_line]
    lines, current = ["["], ""
    for code in codes:
        item = json.dumps(code) + ","
        if current and indent + 4 + len(current) + 1 + len(item) > LINE_WIDTH:
            lines.append(" " * (indent + 4) + current)
            current = item
        else:
            current = f"{current} {item}" if current else item
    lines += [" " * (indent + 4) + current, " " * indent + "]"]
    return lines


def render(locations, url):
    today = datetime.datetime.now(datetime.UTC).strftime("%Y-%m-%d")
    lines = [
        "# BEGIN EDGE SNAPSHOT: generated by refresh_edge_snapshot.py, do not edit by hand.",
        f"# Source: {url}",
        f'EDGE_SNAPSHOT_DATE = "{today}"',
        "EDGE_SNAPSHOT = {",
    ]
    for country, cities in locations.items():
        name = json.dumps(country, ensure_ascii=False)
        one_line = f"    {name}: {json.dumps(cities, ensure_ascii=False)},"
        if len(one_line) <= LINE_WIDTH:
            lines.append(one_line)
            continue
        lines.append(f"    {name}: {{")
        for city, codes in cities.items():
            rendered = _codes(codes, 8)
            rendered[0] = f"        {json.dumps(city, ensure_ascii=False)}: {rendered[0]}"
            rendered[-1] += ","
            lines += rendered
        lines.append("    },")
    lines += ["}", "# END EDGE SNAPSHOT", ""]
    return "\n".join(lines)


def main():
    url = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_URL
    locations = fetch(url)
    if not locations:
        sys.exit("edge list contains no nodes; snapshot not changed")
    source = SOURCE.read_text()
    if not BLOCK_RE.search(source):
        sys.exit(f"EDGE SNAPSHOT markers not found in {SOURCE}")
    SOURCE.write_text(BLOCK_RE.sub(lambda _: render(locations, url), source, count=1))
    cities = sum(len(c) for c in locations.values())
    nodes = sum(len(codes) for c in locations.values() for codes in c.values())
    print(f"{SOURCE.relative_to(ROOT)}: snapshot of {len(locations)} countries, {cities} cities, {nodes} nodes")


if __name__ == "__main__":
    main()
